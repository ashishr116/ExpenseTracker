import Foundation
import SwiftData

// MARK: - Account Type

enum AccountType: String, CaseIterable, Identifiable, Codable {
    case creditCard = "Credit Card"
    case debitCard = "Debit Card"
    case upi = "UPI"
    case cash = "Cash"

    var id: String { rawValue }

    var systemImage: String {
        switch self {
        case .creditCard: "creditcard.fill"
        case .debitCard: "creditcard"
        case .upi: "indianrupeesign.circle"

        case .cash: "banknote"
        }
    }

    /// Whether this account type is linked to a bank.
    var usesBank: Bool { self != .cash }

    /// Whether this account type is linked to a physical card.
    var usesCard: Bool { self == .creditCard || self == .debitCard }
}

