// MARK: - Expense Model

/// A single expense persisted on-device with SwiftData.
///
/// Enums are stored as raw strings so they remain easy to filter in `#Predicate`
/// queries and stay stable if cases are reordered later.
@Model
final class Expense {
    var title: String
    @Attribute(originalName: "amount") private var legacyAmount: Double = 0
    var amountPaise: Int64 = 0
    var accountTypeRaw: String
    var bankName: String
    /// Only the last 4 digits of the card are stored, never the full number.
    var cardLastFour: String
    var categoryRaw: String
    /// A category name typed by the user. Used only when the category is Other; empty otherwise.
    var customCategory: String = ""
    var date: Date
    /// The EMI this expense is an instalment of, if it was generated by one.
    var emi: EMI?
    /// When the user recorded this EMI instalment as actually paid. `nil` means still pending.
    /// Only meaningful for expenses generated by an EMI.
    var paidAt: Date?
    /// The insurance policy this expense is a premium of, if it was generated by one.
    var insurancePolicy: InsurancePolicy?

    init(
        title: String,
        amount: Decimal,
        accountType: AccountType,
        bankName: String,
        cardLastFour: String,
        category: ExpenseCategory,
        date: Date = .now
    ) {
        self.title = title
        self.amountPaise = Money.paise(from: amount)
        self.accountTypeRaw = accountType.rawValue
        self.bankName = bankName
        self.cardLastFour = cardLastFour
        self.categoryRaw = category.rawValue
        self.date = date
    }

    var accountType: AccountType {
        get { AccountType(rawValue: accountTypeRaw) ?? .cash }
        set { accountTypeRaw = newValue.rawValue }
    }

    var amount: Decimal {
        get { amountPaise == 0 && legacyAmount != 0 ? Money.amount(fromLegacy: legacyAmount) : Money.amount(fromPaise: amountPaise) }
        set { amountPaise = Money.paise(from: newValue) }
    }

    func migrateLegacyMoney() {
        guard amountPaise == 0, legacyAmount != 0 else { return }
        amountPaise = Money.paise(from: Money.amount(fromLegacy: legacyAmount))
    }

    /// An EMI instalment or insurance premium that hasn't been recorded as paid yet.
    /// It is a commitment, not money spent, so spending totals leave it out.
    var isPlanned: Bool {
        (emi != nil || insurancePolicy != nil) && paidAt == nil
    }

    /// Fixed spending: EMIs, premiums and categories like rent and groceries. Everything else is variable.
    var isFixedSpending: Bool {
        emi != nil || insurancePolicy != nil || category.isFixed
    }

    var category: ExpenseCategory {
        get { ExpenseCategory(rawValue: categoryRaw) ?? .other }
        set { categoryRaw = newValue.rawValue }
    }

    /// The category as shown to the user: the custom name when one was typed, otherwise the built-in name.
    var categoryName: String {
        let custom = customCategory.trimmingCharacters(in: .whitespacesAndNewlines)
        return category == .other && !custom.isEmpty ? custom : category.rawValue
    }

    /// Title to display, falling back to the category name when no description was entered.
    var displayTitle: String {
        title.isEmpty ? categoryName : title
    }

    /// e.g. "Credit Card · HDFC Bank · •••• 1234"
    var accountDescription: String {
        var parts = [accountType.rawValue]
        if !bankName.isEmpty { parts.append(bankName) }
        if !cardLastFour.isEmpty { parts.append("•••• \(cardLastFour)") }
        return parts.joined(separator: " · ")
    }
}
